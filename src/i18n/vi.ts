// Recursively widen string literal leaves to `string` so other locales can provide translated strings
type DeepWiden<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends readonly string[]
    ? readonly string[]
    : T[K] extends object
    ? DeepWiden<T[K]>
    : T[K];
};

