export const generate30DayStats = (): DailyUsageStat[] => {
  const stats: DailyUsageStat[] = [];
  const baseDate = new Date('2026-11-10');
  
  for (let i = 29; i >= 0; i--) {
    const d = new Date(baseDate);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];
    
    // Create realistic cyclic patterns (lower on weekends)
    const isWeekend = d.getDay() === 0 || d.getDay() === 6;
    const baseMultiplier = isWeekend ? 0.35 : 1.0;
    const variance = (Math.sin(i * 0.5) + 1.2) * 0.4;
    
    const pages = Math.floor((3200 + Math.random() * 1800) * baseMultiplier * (1 + variance));
    const jobs = Math.floor(pages / (3 + Math.random() * 2));
    const failed = Math.floor(jobs * (0.01 + Math.random() * 0.02));
    const avgDurationMs = Math.floor(1800 + Math.random() * 900);
    
    stats.push({
      date: dateStr,
      pages,
      jobs,
      failed,
      avgDurationMs,
    });
  }
  return stats;
};

